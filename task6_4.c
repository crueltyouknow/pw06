#include <stdio.h>

int main(void)
{
    double gb;
    double gb1 = 0.0, gb2 = 0.0, gb3 = 0.0;    /* объем на каждой ступени */
    double cost1, cost2, cost3, total;

    printf("Введите объем хранилища (ГБ): ");
    if (scanf("%lf", &gb) != 1 || gb < 0.0) {
        printf("Ошибка: нужно ввести неотрицательное число\n");
    } else {
        if (gb <= 10.0) {
            gb1 = gb;
        } else if (gb <= 60.0) {
            gb1 = 10.0;
            gb2 = gb - 10.0;
        } else {
            gb1 = 10.0;
            gb2 = 50.0;
            gb3 = gb - 60.0;
        }

        cost1 = gb1 * 1.0;
        cost2 = gb2 * 0.8;
        cost3 = gb3 * 0.5;
        total = cost1 + cost2 + cost3;

        printf("Исходный объем: %.2f ГБ\n", gb);
        printf("Ступень 1 (до 10 ГБ, 1.00/ГБ):      %8.2f ГБ -> %8.2f\n", gb1, cost1);
        printf("Ступень 2 (10-60 ГБ, 0.80/ГБ):      %8.2f ГБ -> %8.2f\n", gb2, cost2);
        printf("Ступень 3 (свыше 60 ГБ, 0.50/ГБ):   %8.2f ГБ -> %8.2f\n", gb3, cost3);
        printf("Итого: %.2f\n", total);
    }

    /*
     * Пояснение: для денежных расчетов предпочтителен double, потому что
     * float хранит лишь около 7 значащих цифр. При крупных суммах и
     * копейках (например, 0.8 или 0.5 за единицу, умноженные на большие
     * объемы) ошибка округления float быстро становится заметной, а у
     * double (около 15-16 цифр) она на много порядков меньше.
     */
    return 0;
}
