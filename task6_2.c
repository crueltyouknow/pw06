#include <stdio.h>
#include <wchar.h>
#include <locale.h>

int main(void)
{
    wint_t c;
    wint_t prev = 0;
    int count = 0;

    /* инициализация локали из окружения (нужна UTF-8 локаль) */
    setlocale(LC_ALL, "");

    printf("Введите текст (завершается символом #):\n");
    while ((c = getwchar()) != WEOF && c != L'#') {
        if (prev == L'е' && c == L'й') {
            count++;
        }
        prev = c;
    }

    printf("Количество вхождений последовательности \"ей\": %d\n", count);

    /*
     * Разница между getchar() и getwchar(): getchar() читает один байт.
     * В многобайтовой кодировке (например, UTF-8) одна кириллическая буква
     * занимает 2 байта, поэтому getchar() вернет ее по частям, и сравнение
     * с одиночным символом будет некорректным. getwchar() читает целый
     * широкий символ (wchar_t/wint_t), декодируя байты согласно текущей
     * локали, поэтому каждая буква приходит как одно значение.
     */
    return 0;
}
