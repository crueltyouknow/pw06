#include <stdio.h>

int main(void)
{
    int n;
    int cnt1 = 0, cnt2 = 0, cnt_eq = 0;
    long sum1 = 0, sum2 = 0;

    printf("Вводите целые числа (0 - конец ввода):\n");

    /* && вычисляется слева направо: n != 0 проверяется, только если scanf
       успешно прочитал число, поэтому неинициализированный n не используется */
    while (scanf("%d", &n) == 1 && n != 0) {
        long a = n < 0 ? -(long)n : n;      /* работаем с модулем */
        int tens = (int)((a / 10) % 10);    /* цифра десятков (для 1-значных = 0) */
        int units = (int)(a % 10);          /* цифра единиц */

        if (tens > units) {
            cnt1++;
            sum1 += n;
        } else if (tens < units) {
            cnt2++;
            sum2 += n;
        } else {
            cnt_eq++;                       /* цифры равны: ни в одной группе */
        }
    }

    printf("Группа 1 (десятки > единицы): %d чисел", cnt1);
    if (cnt1 > 0) {
        printf(", среднее %.2f\n", (double)sum1 / cnt1);
    } else {
        printf(", среднее не определено\n");
    }

    printf("Группа 2 (десятки < единицы): %d чисел", cnt2);
    if (cnt2 > 0) {
        printf(", среднее %.2f\n", (double)sum2 / cnt2);
    } else {
        printf(", среднее не определено\n");
    }

    printf("Числа с равными цифрами десятков и единиц (вне групп): %d\n", cnt_eq);

    /*
     * Ленивое вычисление: в выражении A && B операнд B вычисляется только
     * если A истинно; в выражении A || B операнд B вычисляется только если
     * A ложно. Вычисление идет слева направо, и результат известен сразу,
     * как только он определен левой частью. Поэтому порядок операндов важен:
     * в условии scanf(...) == 1 && n != 0 проверка n выполнится лишь после
     * успешного чтения, а в выражениях вида b != 0 && a / b > 1 деление на
     * ноль не произойдет.
     */
    return 0;
}
